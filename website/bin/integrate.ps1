$ErrorActionPreference = "Stop"

$ConfigStart = "  # jekyll-obsidian:managed-start"
$ConfigEnd = "  # jekyll-obsidian:managed-end"
$WorkflowMarker = "# Generated by website/bin/integrate. Re-run that command instead of editing this file."
$Utf8NoBom = New-Object System.Text.UTF8Encoding($false)
$TemporaryFiles = New-Object System.Collections.Generic.List[string]

function Show-Usage {
    @"
Usage: website\bin\integrate.cmd [options]

Configure a host repository for GitHub Pages without Ruby or Node.js.

Options:
  --source PATH       Repository-relative content directory (default: docs)
  --theme THEME       minimal or docs (default: minimal)
  --check             Verify generated integration files without changing them
  --force-workflow    Replace an existing unmanaged Pages workflow
  --help, -h          Show this help
"@ | Write-Output
}

function Fail([string]$Message) {
    throw "Integration error: $Message"
}

function Fail-UnmanagedConfig {
    Fail @"
.github/jekyll-obsidian.yml is not managed by this command.
Merge this block into a root website mapping, then run the command again:

website:
  # jekyll-obsidian:managed-start
  source: 'docs'
  theme: 'minimal'
  # jekyll-obsidian:managed-end
"@
}

function Read-Utf8Text([string]$Path) {
    return [System.IO.File]::ReadAllText($Path).Replace("`r`n", "`n").Replace("`r", "`n")
}

function Write-Utf8Text([string]$Path, [string]$Content) {
    $normalized = $Content.Replace("`r`n", "`n").Replace("`r", "`n")
    [System.IO.File]::WriteAllText($Path, $normalized, $Utf8NoBom)
}

function Assert-NotReparsePoint([string]$Path, [string]$Label) {
    $item = Get-Item -Force -LiteralPath $Path -ErrorAction SilentlyContinue
    if ($null -ne $item) {
        if (($item.Attributes -band [System.IO.FileAttributes]::ReparsePoint) -ne 0) {
            Fail "$Label must not be a symbolic link, junction, or reparse point."
        }
    }
}

function Test-BytesEqual([string]$First, [string]$Second) {
    if (-not (Test-Path -LiteralPath $First -PathType Leaf) -or
        -not (Test-Path -LiteralPath $Second -PathType Leaf)) {
        return $false
    }
    $left = [System.IO.File]::ReadAllBytes($First)
    $right = [System.IO.File]::ReadAllBytes($Second)
    if ($left.Length -ne $right.Length) { return $false }
    for ($index = 0; $index -lt $left.Length; $index++) {
        if ($left[$index] -ne $right[$index]) { return $false }
    }
    return $true
}

function Test-NormalizedTextEqual([string]$First, [string]$Second) {
    if (-not (Test-Path -LiteralPath $First -PathType Leaf) -or
        -not (Test-Path -LiteralPath $Second -PathType Leaf)) {
        return $false
    }
    $bytes = [System.IO.File]::ReadAllBytes($Second)
    if ($bytes.Length -ge 3 -and $bytes[0] -eq 0xef -and $bytes[1] -eq 0xbb -and $bytes[2] -eq 0xbf) {
        return $false
    }
    return (Read-Utf8Text $First) -ceq (Read-Utf8Text $Second)
}

function Install-Atomic([string]$Temporary, [string]$Target) {
    if (Test-Path -LiteralPath $Target) {
        $backup = "$Target.backup.$([Guid]::NewGuid().ToString('N'))"
        try {
            [System.IO.File]::Replace($Temporary, $Target, $backup, $true)
        }
        finally {
            if (Test-Path -LiteralPath $backup) { Remove-Item -Force -LiteralPath $backup }
        }
    }
    else {
        [System.IO.File]::Move($Temporary, $Target)
    }
    [void]$TemporaryFiles.Remove($Temporary)
}

function Get-ManagedValue([string]$Config, [string]$Key) {
    $blockPattern = "(?ms)^$([Regex]::Escape($ConfigStart))`n(?<body>.*?)^$([Regex]::Escape($ConfigEnd))$"
    $block = [Regex]::Match($Config, $blockPattern)
    if (-not $block.Success) { Fail "the managed configuration block is malformed." }
    $linePattern = "(?m)^  $([Regex]::Escape($Key)): '(?<value>(?:[^']|'')*)'$"
    $matches = [Regex]::Matches($block.Groups["body"].Value, $linePattern)
    if ($matches.Count -ne 1) { Fail "the managed $Key entry is malformed." }
    return $matches[0].Groups["value"].Value.Replace("''", "'")
}

function Assert-ManagedBlockUnderRoot([string]$Config, [string]$Root) {
    $lines = @($Config -split "`n")
    $rootPattern = "^$([Regex]::Escape($Root)):\s*$"
    $rootIndex = -1
    $startIndex = -1
    $endIndex = -1
    for ($index = 0; $index -lt $lines.Count; $index++) {
        if ($lines[$index] -match $rootPattern) { $rootIndex = $index }
        if ($lines[$index] -ceq $ConfigStart) { $startIndex = $index }
        if ($lines[$index] -ceq $ConfigEnd) { $endIndex = $index }
    }
    if ($rootIndex -lt 0 -or $startIndex -le $rootIndex -or $endIndex -le $startIndex) {
        Fail "the managed configuration block must be inside the root $Root mapping."
    }
    for ($index = $rootIndex + 1; $index -le $endIndex; $index++) {
        if ($index -ne $startIndex -and $index -ne $endIndex -and $lines[$index] -match '^[^\s#]') {
            Fail "the managed configuration block must be inside the root $Root mapping."
        }
    }
}

function Escape-YamlSingleQuoted([string]$Value) {
    return $Value.Replace("'", "''")
}

function Escape-WorkflowGlob([string]$Value) {
    $builder = New-Object System.Text.StringBuilder
    foreach ($character in $Value.ToCharArray()) {
        if ("*?+[]!".IndexOf($character) -ge 0) { [void]$builder.Append('\') }
        [void]$builder.Append($character)
    }
    return $builder.ToString()
}

$SourceValue = $null
$ThemeValue = $null
$SourceWasSet = $false
$ThemeWasSet = $false
$CheckOnly = $false
$ForceWorkflow = $false

try {
    for ($index = 0; $index -lt $args.Count; $index++) {
        switch -CaseSensitive ($args[$index]) {
            "--source" {
                if ($index + 1 -ge $args.Count) { Fail "--source requires a value." }
                $index++
                $SourceValue = $args[$index]
                $SourceWasSet = $true
            }
            "--theme" {
                if ($index + 1 -ge $args.Count) { Fail "--theme requires a value." }
                $index++
                $ThemeValue = $args[$index]
                $ThemeWasSet = $true
            }
            "--check" { $CheckOnly = $true }
            "--force-workflow" { $ForceWorkflow = $true }
            "--help" { Show-Usage; exit 0 }
            "-h" { Show-Usage; exit 0 }
            default { Show-Usage; Fail "unknown option: $($args[$index])" }
        }
    }

    $ScriptDir = [System.IO.Path]::GetFullPath($PSScriptRoot)
    $SiteDir = [System.IO.Directory]::GetParent($ScriptDir).FullName
    $HostDir = [System.IO.Directory]::GetParent($SiteDir).FullName
    if ([System.IO.Path]::GetFileName($SiteDir) -cne "website") {
        Fail "the site directory must be named website and live at the host repository root."
    }

    $ConfigPath = Join-Path $HostDir ".github\jekyll-obsidian.yml"
    $WorkflowPath = Join-Path $HostDir ".github\workflows\pages.yml"
    $ConfigTemplate = Join-Path $SiteDir "scripts\templates\host-config.yml"
    $WorkflowTemplate = Join-Path $SiteDir "scripts\templates\pages.yml"
    if (-not (Test-Path -LiteralPath $ConfigTemplate -PathType Leaf)) { Fail "missing host configuration template: website/scripts/templates/host-config.yml" }
    if (-not (Test-Path -LiteralPath $WorkflowTemplate -PathType Leaf)) { Fail "missing Pages workflow template: website/scripts/templates/pages.yml" }

    if ($CheckOnly) {
        if ($SourceWasSet) { Fail "--check cannot be combined with --source." }
        if ($ThemeWasSet) { Fail "--check cannot be combined with --theme." }
        if ($ForceWorkflow) { Fail "--check cannot be combined with --force-workflow." }
        if (-not (Test-Path -LiteralPath $ConfigPath -PathType Leaf)) { Fail "missing .github/jekyll-obsidian.yml; run website/bin/integrate." }
        if (-not (Test-Path -LiteralPath $WorkflowPath -PathType Leaf)) { Fail "missing .github/workflows/pages.yml; run website/bin/integrate." }
    }

    Assert-NotReparsePoint (Join-Path $HostDir ".github") ".github"
    Assert-NotReparsePoint (Join-Path $HostDir ".github\workflows") ".github/workflows"
    Assert-NotReparsePoint $ConfigPath ".github/jekyll-obsidian.yml"
    Assert-NotReparsePoint $WorkflowPath ".github/workflows/pages.yml"
    if ((Test-Path -LiteralPath (Join-Path $HostDir ".github")) -and
        -not (Test-Path -LiteralPath (Join-Path $HostDir ".github") -PathType Container)) { Fail ".github must be a directory." }
    if ((Test-Path -LiteralPath (Join-Path $HostDir ".github\workflows")) -and
        -not (Test-Path -LiteralPath (Join-Path $HostDir ".github\workflows") -PathType Container)) { Fail ".github/workflows must be a directory." }

    $ExistingConfig = $null
    if (Test-Path -LiteralPath $ConfigPath) {
        if (-not (Test-Path -LiteralPath $ConfigPath -PathType Leaf)) { Fail ".github/jekyll-obsidian.yml must be a regular file." }
        $ExistingConfig = Read-Utf8Text $ConfigPath
        $websiteRootCount = ([Regex]::Matches($ExistingConfig, "(?m)^website:\s*$")).Count
        if ($websiteRootCount -ne 1) { Fail-UnmanagedConfig }
        $startCount = ([Regex]::Matches($ExistingConfig, "(?m)^$([Regex]::Escape($ConfigStart))$")).Count
        $endCount = ([Regex]::Matches($ExistingConfig, "(?m)^$([Regex]::Escape($ConfigEnd))$")).Count
        if ($startCount -ne 1 -or $endCount -ne 1) {
            Fail-UnmanagedConfig
        }
        Assert-ManagedBlockUnderRoot $ExistingConfig "website"
        $CurrentSource = Get-ManagedValue $ExistingConfig "source"
        $CurrentTheme = Get-ManagedValue $ExistingConfig "theme"
        if (-not $SourceWasSet) { $SourceValue = $CurrentSource }
        if (-not $ThemeWasSet) { $ThemeValue = $CurrentTheme }
    }
    else {
        if (-not $SourceWasSet) { $SourceValue = "docs" }
        if (-not $ThemeWasSet) { $ThemeValue = "minimal" }
    }

    $SourceValue = $SourceValue.Replace('\', '/')
    if ([string]::IsNullOrEmpty($SourceValue) -or $SourceValue -eq "." -or
        $SourceValue.StartsWith("/") -or $SourceValue -match '^[A-Za-z]:/' -or
        $SourceValue.Contains("//") -or $SourceValue.EndsWith("/") -or
        $SourceValue -match '(^|/)\.\.?($|/)' -or $SourceValue -match '[\x00-\x1f\x7f]') {
        Fail "--source must be a normalized repository-relative directory."
    }
    if ($SourceValue -ne "website/docs" -and
        ($SourceValue -eq "website" -or $SourceValue.StartsWith("website/", [StringComparison]::OrdinalIgnoreCase))) {
        Fail "--source must not overlap website/ except for the bundled website/docs example."
    }
    if (@("minimal", "docs") -cnotcontains $ThemeValue) {
        Fail "--theme must be one of: minimal, docs."
    }

    $CurrentPath = $HostDir
    foreach ($segment in $SourceValue.Split('/')) {
        $CurrentPath = Join-Path $CurrentPath $segment
        Assert-NotReparsePoint $CurrentPath "website.source"
        if (Test-Path -LiteralPath $CurrentPath) {
            $actualName = (Get-Item -Force -LiteralPath $CurrentPath).Name
            if ($actualName -cne $segment) { Fail "--source casing must match the repository path exactly." }
        }
    }
    if (-not (Test-Path -LiteralPath $CurrentPath -PathType Container)) { Fail "website.source does not exist: $SourceValue" }

    if (Test-Path -LiteralPath $WorkflowPath) {
        $existingWorkflow = Read-Utf8Text $WorkflowPath
        if (-not $existingWorkflow.StartsWith("$WorkflowMarker`n") -and $existingWorkflow -ne $WorkflowMarker) {
            if (-not $ForceWorkflow) { Fail ".github/workflows/pages.yml is not managed by this command; rerun with --force-workflow to replace it." }
        }
    }

    $EscapedSource = Escape-YamlSingleQuoted $SourceValue
    $EscapedTheme = Escape-YamlSingleQuoted $ThemeValue
    $EscapedGlob = Escape-YamlSingleQuoted "$(Escape-WorkflowGlob $SourceValue)/**"

    if ($null -ne $ExistingConfig) {
        $blockPattern = "(?ms)^$([Regex]::Escape($ConfigStart))`n.*?^$([Regex]::Escape($ConfigEnd))$"
        $managedBlock = "$ConfigStart`n  source: '$EscapedSource'`n  theme: '$EscapedTheme'`n$ConfigEnd"
        $DesiredConfig = [Regex]::Replace($ExistingConfig, $blockPattern, [System.Text.RegularExpressions.MatchEvaluator]{ param($match) $managedBlock })
    }
    else {
        $DesiredConfig = Read-Utf8Text $ConfigTemplate
        $DesiredConfig = $DesiredConfig.Replace("__JEKYLL_WEBSITE_SOURCE__", $EscapedSource)
        $DesiredConfig = $DesiredConfig.Replace("__JEKYLL_WEBSITE_THEME__", $EscapedTheme)
    }
    $DesiredWorkflow = (Read-Utf8Text $WorkflowTemplate).Replace("__JEKYLL_WEBSITE_SOURCE_GLOB__", $EscapedGlob)
    if (-not $DesiredConfig.EndsWith("`n")) { $DesiredConfig += "`n" }
    if (-not $DesiredWorkflow.EndsWith("`n")) { $DesiredWorkflow += "`n" }

    if ($CheckOnly) {
        $ConfigTemporary = [System.IO.Path]::GetTempFileName()
        $WorkflowTemporary = [System.IO.Path]::GetTempFileName()
    }
    else {
        $GithubDir = Join-Path $HostDir ".github"
        $WorkflowsDir = Join-Path $GithubDir "workflows"
        [System.IO.Directory]::CreateDirectory($WorkflowsDir) | Out-Null
        $ConfigTemporary = Join-Path $GithubDir ".$([Guid]::NewGuid().ToString('N')).config.tmp"
        $WorkflowTemporary = Join-Path $WorkflowsDir ".$([Guid]::NewGuid().ToString('N')).workflow.tmp"
    }
    [void]$TemporaryFiles.Add($ConfigTemporary)
    [void]$TemporaryFiles.Add($WorkflowTemporary)
    Write-Utf8Text $ConfigTemporary $DesiredConfig
    Write-Utf8Text $WorkflowTemporary $DesiredWorkflow

    if ($CheckOnly) {
        if (-not (Test-NormalizedTextEqual $ConfigTemporary $ConfigPath)) { Fail ".github/jekyll-obsidian.yml is not normalized; run website/bin/integrate." }
        if (-not (Test-NormalizedTextEqual $WorkflowTemporary $WorkflowPath)) { Fail ".github/workflows/pages.yml is out of sync; run website/bin/integrate." }
        Write-Output "Host integration is valid for $SourceValue using the $ThemeValue theme."
        exit 0
    }

    if (-not (Test-BytesEqual $ConfigTemporary $ConfigPath)) { Install-Atomic $ConfigTemporary $ConfigPath }
    if (-not (Test-BytesEqual $WorkflowTemporary $WorkflowPath)) { Install-Atomic $WorkflowTemporary $WorkflowPath }

    Write-Output "Configured $SourceValue with the $ThemeValue theme."
    Write-Output "Generated .github/jekyll-obsidian.yml and .github/workflows/pages.yml."
    Write-Output "Next: in GitHub, choose Settings > Pages > Build and deployment > Source > GitHub Actions, then commit and push these files."
}
catch {
    [Console]::Error.WriteLine($_.Exception.Message)
    exit 1
}
finally {
    foreach ($path in $TemporaryFiles) {
        if (Test-Path -LiteralPath $path) { Remove-Item -Force -LiteralPath $path }
    }
}
